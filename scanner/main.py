def build_stock_dict(
    stocks: list[dict],
    extra_us_stocks: list[tuple[list[str], str, str, str]] | None = None,
    dynamic_us: list[dict] | None = None,
    tw_industry_map: dict[str, str] | None = None,
    etf_full_names: dict[str, str] | None = None,
) -> tuple[dict[str, str], dict[str, str], dict[str, str], dict[str, str]]:
    """
    從台股清單 + US built-in dict 建立：
    - stock_dict:   keyword → code
    - code_to_name: code → canonical name
    - stock_market: code → "TW" | "US"
    - stock_sector: code → sector name
    """
    code_to_name: dict[str, str] = {}
    stock_dict:   dict[str, str] = {}
    stock_market: dict[str, str] = {}
    stock_sector: dict[str, str] = {}

    # Common suffixes to strip when generating short-name aliases
    _TW_SUFFIXES = [
        "股份有限公司", "有限公司",
        "投資控股", "投控", "控股",
        "光電工業", "光電", "電子工業", "電子",
        "科技工業", "科技", "電腦", "工業", "企業", "實業", "國際",
    ]

    def _short_aliases(name: str) -> list[str]:
        """Strip trailing suffixes repeatedly to generate spoken short names.
        e.g. "聯亞光電工業" → ["聯亞光電", "聯亞"]
        """
        aliases = []
        current = name
        while True:
            stripped = False
            for suffix in _TW_SUFFIXES:
                if current.endswith(suffix):
                    current = current[: -len(suffix)]
                    if len(current) >= 2:
                        aliases.append(current)
                    stripped = True
                    break
            if not stripped:
                break
        return aliases

    # ── Taiwan stocks (TWSE / TPEx) ───────────────────────────────────────
    for s in stocks:
        code = s["code"]
        name = s["name"]
        # 清理 ETF 名稱備註，如「(原簡稱:群益台灣ESG低碳)」
        if re.match(r"^0\d{3,5}[A-Z]?$", code):
            name = re.sub(r"\(原簡稱[：:][^)]+\)", "", name).strip()
        code_to_name[code] = name
        stock_dict[name]   = code
        stock_dict[code]   = code
        stock_market[code] = "TW"
        if code in TW_STOCK_SECTORS:
            stock_sector[code] = TW_STOCK_SECTORS[code]
        elif tw_industry_map and code in tw_industry_map:
            stock_sector[code] = tw_industry_map[code]
        # Also register short spoken name (e.g. "華通電腦" → "華通")
        # ETF codes are excluded — their names are already in full, and
        # shortened aliases (e.g. "永續高股息") cause too many false positives
        # in financial content where these phrases appear in non-ETF contexts.
        if not re.match(r"^0\d{3,5}[A-Z]?$", code):
            for short in _short_aliases(name):
                if short not in stock_dict:
                    stock_dict[short] = code
        # For ETF codes: also register the full official name from cache if different
        if re.match(r"^0\d{3,5}[A-Z]?$", code) and etf_full_names and code in etf_full_names:
            full_name = re.sub(r"\(原簡稱[：:][^)]+\)", "", etf_full_names[code]).strip()
            if full_name and full_name not in stock_dict:
                stock_dict[full_name] = code

    # ── US stocks (built-in) — added BEFORE aliases so aliases can override ─
    for kw, ticker in US_KEYWORD_TO_CODE.items():
        if re.match(r'^[A-Za-z]$', kw):
            continue  # single-letter tickers cause too many false positives in Chinese text
        stock_dict[kw] = ticker
    for ticker, info in US_CODE_TO_INFO.items():
        if ticker not in code_to_name:
            code_to_name[ticker] = info["name"]
        stock_market[ticker] = "US"
        stock_sector[ticker] = info["sector"]

    # ── US stocks (Gemini-enriched extra) ─────────────────────────────────
    # Hard blocklist: generic financial/tech terms Gemini may suggest but are NOT stock identifiers
    _GENERIC_FINANCE_TERMS = {
        "ETF", "IPO", "EPS", "PE", "PB", "ROE", "ROA", "AUM", "NAV",
        "GDP", "CPI", "Fed", "ECB", "IMF", "SPX", "VIX", "USD", "EUR",
        "AI", "API", "ESG",
    }
    for kws, ticker, name, sector in (extra_us_stocks or []):
        if ticker not in code_to_name:
            code_to_name[ticker] = name
        stock_market[ticker] = "US"
        stock_sector[ticker] = sector
        for kw in kws:
            if not re.match(r'^[A-Za-z0-9]', kw):
                continue  # skip non-ASCII (Chinese) aliases — too many false positives
            if len(kw) < 2:
                continue  # single-letter keywords are too noisy
            if kw.upper() in _GENERIC_FINANCE_TERMS:
                continue  # skip generic terms that cause mass false positives
            if kw not in stock_dict:  # don't override hardcoded entries
                stock_dict[kw] = ticker

    # ── US stocks (S&P 500 + EDGAR dynamic, lowest US priority) ──────────
    _known_us = set(US_CODE_TO_INFO.keys()) | {t for _, t, _, _ in (extra_us_stocks or [])}
    _us_name_suffixes = [
        " Inc.", " Inc", " Corp.", " Corp", " Corporation",
        " LLC", " Ltd.", " Ltd", " Co.", " Holdings", " Group",
        " L.P.", " LP", " plc", " PLC",
    ]

    def _strip_us_name(name: str) -> str:
        for suffix in _us_name_suffixes:
            if name.endswith(suffix):
                return name[:-len(suffix)].strip()
        return name

    for s in (dynamic_us or []):
        ticker = s["code"]
        name   = s["name"]
        sector = s.get("sector", "其他")
        if ticker in _known_us:
            continue  # already covered by hardcoded or Gemini
        if ticker not in code_to_name:
            code_to_name[ticker] = name
        stock_market[ticker] = "US"
        if ticker not in stock_sector:
            stock_sector[ticker] = sector

        # EDGAR-only stocks (sector="其他") are not added to stock_dict at all:
        # their tickers are too short/generic and they have no usable sector.
        # S&P 500 stocks (sector != "其他") get name-based + 4+-char ticker recognition.
        if sector == "其他":
            continue

        # Full company name (≥5 chars)
        if len(name) >= 5 and name not in stock_dict:
            stock_dict[name] = ticker
        # Stripped name (without Inc./Corp. etc.)
        stripped = _strip_us_name(name)
        if stripped != name and len(stripped) >= 5 and stripped not in stock_dict:
            stock_dict[stripped] = ticker
        # Ticker only if ≥4 chars (shorter ones cause false positives in Chinese text)
        if len(ticker) >= 4 and ticker not in stock_dict:
            stock_dict[ticker] = ticker

    # ── Taiwan aliases (override conflicts; TW wins over US for same keyword) ─
    for alias, code in ALIASES.items():
        stock_dict[alias] = code
        if re.match(r"^\d{4,6}$", alias) and alias not in code_to_name:
            code_to_name[alias] = alias
        if code not in stock_market:
            stock_market[code] = "TW"

