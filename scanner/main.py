def _detect_youtube_video(
    video: dict, source_name: str
) -> tuple[dict, list[dict], str, str]:
    """
    Pass 1: 取得逐字稿並辨識股票。
    回傳 (video_entry, hits, analysis_source, video_url)。
    不呼叫 Gemini sentiment（由頻道層級 batch 處理）。
    """
