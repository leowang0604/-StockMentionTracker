    TWSE_RWD_URL = "https://www.twse.com.tw/rwd/zh/afterTrading/STOCK_DAY_ALL"      # fallback, works in Actions
    TPEX_URL     = "https://www.tpex.org.tw/openapi/v1/mopsfin_t187ap03_O"
